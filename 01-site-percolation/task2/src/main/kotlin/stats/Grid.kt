package stats

import kotlin.math.pow

/**
 * Разбиение решётки L x L на k x k интервалов для критерия Пирсона.
 *
 * Интервалы нумеруются построчно: интервал `(ix, iy)` имеет индекс `iy * k + ix`.
 *
 * @property size линейный размер решётки L
 * @property occupied число занятых узлов n, от него зависит k
 */
class Grid(val size: Int, val occupied: Int) {

    /** Число интервалов по одной оси. */
    val k: Int

    /** Общее число интервалов. */
    val m: Int
        get() = k * k

    init {
        require(occupied > 0) { "Нужен хотя бы один занятый узел: $occupied" }

        // модификация формулы Скотта: для куба m = ([(2n/3)^(1/9)] + 1)³...
        // на плоскости по тому же принципу k = [(2n/3)^(1/6)] + 1 и m = k², поэтому общее
        // число интервалов растёт как n^(1/3), как у Скотта в одномерном случае.

        // целая часть корня перебором: наибольшее root, для которого 3 * root^6 <= 2n.
        // pow(1.0 / 6) на точной шестой степени даёт 3.999... вместо 4 и теряет единицу

        // ceil не подойдёт: когда корень целый, k выходит на 1 меньше формулы (например, при n = 96)

        var root = 0
        while (3 * (root + 1.0).pow(6) <= 2.0 * occupied) root++
        this.k = root + 1
    }

    // c * k / L для каждой координаты, т.к. считать деление на каждый узел в каждом испытании — дорого
    private val intervals = IntArray(size) { it * k / size }

    /** Индекс интервала, в который попадает узел `(x, y)`. */
    fun indexOf(x: Int, y: Int): Int =
        intervals[y] * k + intervals[x]

    /** Первая координата интервала [j] по одной оси, `start(k) == L`. */
    fun startOf(j: Int): Int =
        (j * size + k - 1) / k

    /**
     * Ожидаемое число занятых узлов в интервале [index] при равномерном заполнении.
     *
     * L не обязан делиться на k, и интервалы отличаются шириной на узел.
     * Поэтому ожидание берётся по доле площади, а не n / m: иначе критерий ловил бы неравномерность нарезки.
     */
    fun expected(index: Int): Double {
        val area = widthOf(index % k) * widthOf(index / k)
        return occupied * (area.toDouble() / size / size)
    }

    private fun widthOf(j: Int): Int =
        startOf(j + 1) - startOf(j)

}
